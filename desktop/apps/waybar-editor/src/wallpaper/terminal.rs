use super::theme::{Palette, Paths, contrasting_text, replace_block, write_atomic_with_mode};
use anyhow::{Context, Result, bail};
use std::fmt::Write;
use std::fs;
use std::os::unix::fs::PermissionsExt;

pub(super) fn sync(
    paths: &Paths,
    palette: &Palette,
    command: impl Fn(&str, &[&str]) -> Result<()>,
) -> Result<()> {
    palette.validate()?;
    let metadata = match fs::symlink_metadata(&paths.kitty) {
        Ok(metadata) => metadata,
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => return Ok(()),
        Err(error) => return Err(error).context("No se pudo revisar la configuración de Kitty"),
    };
    if metadata.file_type().is_symlink() {
        bail!(
            "No se reemplazan enlaces simbólicos: {}",
            paths.kitty.display()
        );
    }
    let original = fs::read_to_string(&paths.kitty)?;
    let updated = themed_config(&original, palette)?;
    write_atomic_with_mode(
        &paths.kitty,
        updated.as_bytes(),
        metadata.permissions().mode() & 0o777,
    )?;
    // SIGUSR1 reloads Kitty's configuration without closing its shells.
    command("pkill", &["-SIGUSR1", "-x", "kitty"])
        .context("Colores guardados; no se pudo solicitar la recarga de Kitty")
}

fn mix(first: &str, second: &str, amount: f64) -> String {
    let channel = |color: &str, start| u8::from_str_radix(&color[start..start + 2], 16).unwrap();
    let [red, green, blue] = [1, 3, 5].map(|i| {
        (f64::from(channel(first, i)) * (1.0 - amount) + f64::from(channel(second, i)) * amount)
            .round() as u8
    });
    format!("#{red:02x}{green:02x}{blue:02x}")
}

fn themed_config(original: &str, palette: &Palette) -> Result<String> {
    palette.validate()?;
    let Palette {
        accent,
        secondary,
        background,
        foreground,
    } = palette;
    let surface = mix(background, foreground, 0.08);
    let muted = mix(background, foreground, 0.72);
    let on_accent = contrasting_text(accent);
    let mut colors = format!(
        "# Generated by Wallpaper Studio.\n\
foreground {foreground}\nbackground {background}\n\
cursor {accent}\ncursor_text_color {on_accent}\n\
selection_background {accent}\nselection_foreground {on_accent}\n\
url_color {secondary}\nactive_border_color {accent}\ninactive_border_color {surface}\n\
active_tab_background {accent}\nactive_tab_foreground {on_accent}\n\
inactive_tab_background {surface}\ninactive_tab_foreground {muted}\n\
tab_bar_background {background}\n"
    );
    // Keep red/green/yellow recognizable for errors, success and warnings,
    // while tinting them towards the wallpaper's two accents.
    let ansi = [
        background.clone(),
        mix("#e06c75", secondary, 0.16),
        mix("#69b884", accent, 0.12),
        mix("#e0bd68", secondary, 0.12),
        accent.clone(),
        secondary.clone(),
        mix(accent, secondary, 0.5),
        mix(foreground, background, 0.12),
    ];
    for (index, color) in ansi.iter().enumerate() {
        writeln!(colors, "color{index} {color}")?;
        let bright = if index == 7 {
            foreground.clone()
        } else {
            mix(color, foreground, 0.25)
        };
        writeln!(colors, "color{} {bright}", index + 8)?;
    }
    replace_block(
        original,
        "# wallpaper-studio:begin",
        "# wallpaper-studio:end",
        &colors,
    )
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::cell::RefCell;

    fn palette() -> Palette {
        Palette {
            accent: "#2c80e0".into(),
            secondary: "#e865a3".into(),
            background: "#0c1323".into(),
            foreground: "#ebeef4".into(),
        }
    }

    #[test]
    fn replaces_colors_without_changing_font_opacity_or_shortcuts() {
        let original = "font_family monospace\nbackground_opacity 0.82\nmap ctrl+a send_text all test\nbackground #000000\n";
        let first = themed_config(original, &palette()).unwrap();
        assert!(first.starts_with(original.trim_end()));
        for setting in [
            "foreground #ebeef4",
            "background #0c1323",
            "cursor #2c80e0",
            "selection_background #2c80e0",
            "color4 #2c80e0",
            "color5 #e865a3",
            "color15 #ebeef4",
        ] {
            assert!(first.contains(setting), "Missing: {setting}");
        }
        let ansi: Vec<_> = first
            .lines()
            .filter(|line| line.starts_with("color"))
            .collect();
        assert_eq!(ansi.len(), 16);
        let mut changed = palette();
        changed.accent = "#bb99ff".into();
        let updated = themed_config(&first, &changed).unwrap();
        assert_eq!(updated.matches("# wallpaper-studio:begin").count(), 1);
        assert!(updated.starts_with(original.trim_end()));
        assert!(!updated.contains("#2c80e0"));
        assert_eq!(themed_config(&updated, &changed).unwrap(), updated);
        assert!(themed_config("# wallpaper-studio:begin", &changed).is_err());
        changed.accent = "#ffffff\nfont_size 99".into();
        assert!(themed_config(original, &changed).is_err());
    }

    #[test]
    fn sync_skips_absent_config_reloads_existing_and_rejects_symlinks() {
        let temp = tempfile::tempdir().unwrap();
        let paths = Paths {
            wallpapers: temp.path().join("images"),
            state: temp.path().join("state.json"),
            style: temp.path().join("style.css"),
            hypr: temp.path().join("local.conf"),
            control_style: temp.path().join("control.scss"),
            kitty: temp.path().join("kitty.conf"),
        };
        sync(&paths, &palette(), |_, _| panic!("Kitty is not configured")).unwrap();
        assert!(!paths.kitty.exists());
        fs::write(&paths.kitty, "font_size 10.5\n").unwrap();
        fs::set_permissions(&paths.kitty, fs::Permissions::from_mode(0o640)).unwrap();
        let calls = RefCell::new(Vec::new());
        sync(&paths, &palette(), |program, args| {
            calls
                .borrow_mut()
                .push((program.to_owned(), args.join(" ")));
            Ok(())
        })
        .unwrap();
        assert_eq!(
            *calls.borrow(),
            [("pkill".into(), "-SIGUSR1 -x kitty".into())]
        );
        assert_eq!(
            fs::metadata(&paths.kitty).unwrap().permissions().mode() & 0o777,
            0o640
        );
        let original = fs::read(&paths.kitty).unwrap();
        assert!(sync(&paths, &palette(), |_, _| bail!("reload unavailable")).is_err());
        assert_eq!(fs::read(&paths.kitty).unwrap(), original);
        let private = temp.path().join("private");
        fs::write(&private, "untouched").unwrap();
        fs::remove_file(&paths.kitty).unwrap();
        std::os::unix::fs::symlink(&private, &paths.kitty).unwrap();
        assert!(sync(&paths, &palette(), |_, _| panic!("must not reload")).is_err());
        assert_eq!(fs::read_to_string(private).unwrap(), "untouched");
    }
}
